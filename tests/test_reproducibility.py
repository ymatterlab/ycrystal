def test_snapshot_fixes_camera_and_size_and_keeps_the_structure(tmp_path):
    project = load_input(FIXTURES / "BaZrO3.cif")
    styled, _ = apply_style_file(project, STYLE, element_map={"Ti": "Zr"}, camera_kept=False)
    view = ViewPolicy(view="a")
    geometry, camera, settings = scene_for(styled, 500, None, view)
    snapshot = snapshot_project(styled, 500, None, view)
    assert snapshot.camera == camera and (snapshot.output.width, snapshot.output.height) == (
        500,
        600,
    )
    assert snapshot.scene == styled.scene and snapshot.environment == styled.environment
    for name in ("cell", "positions", "numbers"):
        assert np.array_equal(getattr(snapshot.structure, name), getattr(project.structure, name))
    source = snapshot.structure.metadata["source"]
    assert "path" not in source and source["sha256"] == sha(FIXTURES / "BaZrO3.cif")
    assert "path" in project.structure.metadata["source"]  # the input is not changed

    reopened = load_project(save_project(tmp_path / "Bild ü.ycrystal", snapshot))
    again, camera2, settings2 = scene_for(reopened)  # no options: as saved
    assert camera2 == camera
    for name in ("width", "height", "antialias", "transparent_background"):
        assert getattr(settings2, name) == getattr(settings, name)
    for name in ("positions", "radii", "colors"):
        assert np.array_equal(getattr(again, name), getattr(geometry, name)), name
    assert list(again.materials) == list(geometry.materials)
    assert dict(reopened.scene.element_materials)["Zr"] == "chrome"  # mapping resolved


@pytest.mark.parametrize(
    "source, style, mapping, view, size",
    [
        ("BaZrO3.cif", STYLE, {"Ti": "Zr"}, ViewPolicy(view="a", visible_height=9.0), (320, 320)),
        (AFM, STYLE, None, ViewPolicy(camera="fit"), (None, None)),  # vectors, refitted
        (ROOT / "examples" / "SrTiO3-studio.ycrystal", None, None, ViewPolicy(), (400, None)),
        ("MgB2.cif", None, None, ViewPolicy(), (None, None)),  # default view, fitted
        ("triclinic.cif", None, None, ViewPolicy(view="c", margin=0.2), (300, 500)),
    ],
)
def test_replaying_a_snapshot_writes_the_same_scene(tmp_path, source, style, mapping, view, size):
    project = load_input(FIXTURES / source if isinstance(source, str) else source)
    if style is not None:
        kept = view.policy == "saved"
        project, _ = apply_style_file(project, style, element_map=mapping, camera_kept=kept)
    (tmp_path / "first").mkdir()
    (tmp_path / "replay").mkdir()
    export_scene(project, tmp_path / "first" / "scene.pov", *size, view)
    saved = save_project(tmp_path / "figure.ycrystal", snapshot_project(project, *size, view))
    export_scene(load_project(saved), tmp_path / "replay" / "scene.pov")  # no options
    first, replay = tmp_path / "first", tmp_path / "replay"
    assert pov_body(replay / "scene.pov") == pov_body(first / "scene.pov")
    assert (replay / "scene.ini").read_text() == (first / "scene.ini").read_text()


