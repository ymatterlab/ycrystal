def assert_same_pixels(first: Path, second: Path) -> None:
    a, b = load_rgba(first).astype(int), load_rgba(second).astype(int)
    assert a.shape == b.shape
    assert np.abs(a - b).max() <= PIXEL_TOLERANCE


