def snapshot_manifest(folder: Path, **extra) -> Path:
    folder.mkdir(parents=True, exist_ok=True)
    data = {
        "format": "ycrystal-batch",
        "schema_version": 1,
        "save_projects": True,
        "defaults": {"style": str(STYLE), "view": "a", "width": 240, "height": 180},
        "jobs": [
            {"id": "SrTiO3", "input": str(FIXTURES / "SrTiO3.cif")},
            {"id": "BaZrO3", "input": str(FIXTURES / "BaZrO3.cif"), "element_map": {"Ti": "Zr"}},
            {"id": "afm", "input": str(AFM), "output": "vectors/afm.png", "camera_policy": "fit"},
        ],
        **extra,
    }
    path = folder / "series ü.json"
    path.write_text(json.dumps(data), encoding="utf-8")
    return path


def test_batch_saves_a_snapshot_and_record_per_job(tmp_path, capsys):
    manifest = snapshot_manifest(tmp_path / "Serie")
    out = tmp_path / "renders"
    assert main(["--batch", str(manifest), "--output-dir", str(out), "--dry-run"]) == 0
    stdout = capsys.readouterr().out
    assert "SrTiO3: would render SrTiO3.png and save SrTiO3.ycrystal (240 × 180" in stdout
    assert "afm: would render vectors/afm.png and save vectors/afm.ycrystal" in stdout
    assert not out.exists()
    povray = fake_povray(tmp_path)
    assert main(["--batch", str(manifest), "--output-dir", str(out), "--povray", povray]) == 0
    report = json.loads((out / REPORT_NAME).read_text(encoding="utf-8"))
    assert [(j["project"], j["provenance"]) for j in report["jobs"]] == [
        ("SrTiO3.ycrystal", "SrTiO3.provenance.json"),
        ("BaZrO3.ycrystal", "BaZrO3.provenance.json"),
        ("vectors/afm.ycrystal", "vectors/afm.provenance.json"),
    ]
    for job in report["jobs"]:
        record = json.loads((out / job["provenance"]).read_text(encoding="utf-8"))
        assert record["job"] == job["id"] and record["manifest"]["sha256"] == sha(manifest)
        assert record["manifest"]["name"] == "series ü.json"
        assert record["image"]["sha256"] == sha(out / job["output"])
        assert record["project"]["sha256"] == sha(out / job["project"])
        assert record["notes"] == job["warnings"]
    afm = json.loads((out / "vectors" / "afm.provenance.json").read_text(encoding="utf-8"))
    assert afm["replay"] == "ycrystal afm.ycrystal --render afm.png"  # in its own folder
    assert afm["input"]["format"] == "project"
    zr = load_project(out / "BaZrO3.ycrystal")
    assert dict(zr.scene.element_materials)["Zr"] == "chrome" and zr.camera is not None
    assert load_project(out / "vectors" / "afm.ycrystal").scene.vectors == (
        load_input(AFM).scene.vectors
    )
    assert not [p for p in out.rglob("*") if p.name.startswith(".ycrystal-")]
    capsys.readouterr()
    assert main(["--batch", str(manifest), "--output-dir", str(out), "--povray", povray]) == 2
    assert "SrTiO3.png exists; use --overwrite" in capsys.readouterr().err  # first problem


def test_batch_snapshot_validation(tmp_path):
    with pytest.raises(ManifestError, match="save_projects must be true or false"):
        plan_batch(snapshot_manifest(tmp_path / "a", save_projects="yes"), tmp_path / "out")
    # A snapshot would replace an input that lives in the output folder.
    out = tmp_path / "out"
    out.mkdir()
    shutil.copyfile(AFM, out / "afm.ycrystal")
    jobs = [{"id": "afm", "input": str(out / "afm.ycrystal")}]
    manifest = snapshot_manifest(tmp_path / "b", jobs=jobs)
    with pytest.raises(ManifestError) as info:
        plan_batch(manifest, out, overwrite=True)
    assert info.value.problems == [
        f"job afm: {out / 'afm.ycrystal'} would replace a file the figure is made from or "
        "written to."
    ]
    (out / "afm.ycrystal").unlink()
    (out / "SrTiO3.provenance.json").write_text("{}")
    with pytest.raises(ManifestError, match="SrTiO3.provenance.json exists"):
        plan_batch(snapshot_manifest(tmp_path / "c"), out)
    # Without save_projects nothing changes: no snapshot planned, none reported.
    plain = snapshot_manifest(tmp_path / "d", save_projects=False)
    assert {job.snapshot for job in plan_batch(plain, tmp_path / "out2")} == {None}


