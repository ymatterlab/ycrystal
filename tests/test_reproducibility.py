    assert (replay / picture.filename).read_bytes() == picture.data  # staged from the package
    assert "Shiny" in (replay / "scene.pov").read_text(encoding="utf-8")
    again = load_project(snapshot)  # in this process too, from a clean registry
    assert again.scene.vectors == afm.scene.vectors and again.environment.image is not None
    assert dict(again.scene.element_materials)["Fe"] == shiny.id


