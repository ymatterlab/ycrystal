    assert is_package(style_path)
    digests = {"input": sha(target_path), "style": sha(style_path)}
    out = tmp_path / "Abbildung"
    parts = ["--style-parts", "environment,output", "--camera-policy", "fit"]
    args = [str(target_path), "--style", str(style_path), *parts, "--render"]
